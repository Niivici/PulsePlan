CREATE TABLE event_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL,
    scene VARCHAR(120) NOT NULL,
    color VARCHAR(16) NOT NULL,
    UNIQUE (account_id, id)
);

CREATE TABLE schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    event_block_id BIGINT NOT NULL,
    title VARCHAR(120) NOT NULL,
    day_key DATE NOT NULL,
    start_minute INTEGER NOT NULL,
    end_minute INTEGER NOT NULL,
    completed BOOLEAN NOT NULL DEFAULT FALSE,
    FOREIGN KEY (account_id, event_block_id) REFERENCES event_blocks(account_id, id),
    CHECK (start_minute >= 0 AND end_minute <= 1440 AND start_minute < end_minute)
);

CREATE INDEX schedules_account_date ON schedules(account_id, day_key, start_minute);

CREATE TABLE reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT NOT NULL REFERENCES schedules(id) ON DELETE CASCADE,
    title VARCHAR(120) NOT NULL,
    remind_minute INTEGER NOT NULL CHECK (remind_minute >= 0 AND remind_minute < 1440),
    intensity VARCHAR(40) NOT NULL
);

CREATE INDEX reminders_schedule ON reminders(schedule_id);
